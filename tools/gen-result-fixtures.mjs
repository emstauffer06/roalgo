// Regenerates the Luau-printed cross-language fixtures that BOTH sides read:
//   lab/tests/fixtures/PrngVectors.luau   (PRNG sequences; checked by Export.spec.luau and validate-results.test.mjs)
//   lab/tests/fixtures/ExportSample.luau  (ResultStore pages + Luau metrics for a synthetic run)
// Each file is a Luau module `return [==[<compact JSON>]==]`, so Luau `require`s it and Node extracts the same bytes.
// Usage (project root): node tools/gen-result-fixtures.mjs     LUAU_EXE overrides the luau binary path.
// Node 24, built-in modules only; runs the local luau binary, no network.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, renameSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const FIXTURE_DIR = join(root, "lab", "tests", "fixtures");
export const FIXTURES = ["PrngVectors", "ExportSample"];
const DEFAULT_LUAU = (process.env.LUAU_EXE || "luau");
const OPEN = "return [==[";
const CLOSE = "]==]";

export function wrapFixture(name, json) {
  if (json.includes(CLOSE)) throw new Error(`gen-result-fixtures: ${name} JSON contains ${CLOSE}`);
  if (/[\r\n]/.test(json)) throw new Error(`gen-result-fixtures: ${name} JSON must be a single line`);
  return (
    `-- GENERATED by tools/gen-result-fixtures.mjs from lab/tests/fixtures/${name}Builder.luau. Do not edit by hand.\n` +
    `-- Read by lab/tests/Export.spec.luau (require) and tools/validate-results.test.mjs (readFixture).\n` +
    `${OPEN}${json}${CLOSE}\n`
  );
}

export function unwrapFixture(text) {
  const start = text.indexOf(OPEN);
  const end = text.lastIndexOf(CLOSE);
  if (start < 0 || end < start) throw new Error("gen-result-fixtures: not a wrapped fixture module");
  return text.slice(start + OPEN.length, end);
}

// Returns the fixture's JSON text exactly as Luau's require sees it.
export function readFixtureText(name) {
  const bytes = readFileSync(join(FIXTURE_DIR, `${name}.luau`));
  return unwrapFixture(new TextDecoder("utf-8", { fatal: true }).decode(bytes));
}

export function readFixture(name) {
  return JSON.parse(readFixtureText(name));
}

function generate(name, luau) {
  const out = execFileSync(luau, ["lab/tests/fixtures/PrintFixture.luau", "-a", name], { cwd: root, maxBuffer: 64 << 20 });
  const json = new TextDecoder("utf-8", { fatal: true }).decode(out).replace(/\r?\n$/, "");
  JSON.parse(json); // must be valid JSON
  const target = join(FIXTURE_DIR, `${name}.luau`);
  const tmp = `${target}.tmp`;
  writeFileSync(tmp, wrapFixture(name, json), "utf8");
  renameSync(tmp, target);
  return { target, bytes: Buffer.byteLength(json, "utf8") };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const luau = process.env.LUAU_EXE || DEFAULT_LUAU;
  for (const name of FIXTURES) {
    const { target, bytes } = generate(name, luau);
    console.log(`wrote ${target} (${bytes} JSON bytes)`);
  }
}
